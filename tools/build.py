"""Python stand-in for tools/build.cjs (this PC has no Node): bundles src/ into mod/main.js with identical output.
Writes main.js only; modinfo.json and the placeholder preview stay build.cjs's job.

    python -I tools/build.py [--check]
"""
import json, os, re, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
src = lambda f: open(os.path.join(ROOT, "src", f), encoding="utf-8", newline="").read()
VERSION = re.search(r'const VERSION = "([^"]+)"', open(os.path.join(ROOT, "tools", "build.cjs"), encoding="utf-8").read()).group(1)
js = lambda s: json.dumps(s, ensure_ascii=False)  # same escapes as JSON.stringify for these sources

bundle = "\n".join([
    "// GENERATED by tools/build.cjs from src/. Edit src/, then run: node tools/build.cjs",
    f"const VERSION = {js(VERSION)};",
    f"const LOGIC_SRC = {js(src('logic.js'))};",
    f"const WORKER_SRC = {js(src('worker.js'))};",
    src("logic.js"), src("capture.js"), src("ui.js"),
])
path = os.path.join(ROOT, "mod", "main.js")
if "--check" in sys.argv:
    same = open(path, encoding="utf-8", newline="").read() == bundle
    print("mod/main.js is current" if same else "mod/main.js is stale"); sys.exit(0 if same else 1)
open(path, "w", encoding="utf-8", newline="").write(bundle)
print(f"Built mod/main.js ({len(bundle) // 1024} KB), version {VERSION}")
