"use strict";
// Bundles src/ into mod/main.js (a mod entry runs inside an async IIFE: no import/export),
// writes mod/modinfo.json, and a placeholder mod/preview.png only if there is none (the real one
// comes from tools/make_art.py). `--check` fails if mod/ is stale.
// The in-game uploader sends name -> Steam title, description -> Steam description, version ->
// change note. The description is plain text: it also shows in the game's mod list.
const fs = require("node:fs"), path = require("node:path"), zlib = require("node:zlib");
const root = path.join(__dirname, ".."), src = (f) => fs.readFileSync(path.join(root, "src", f), "utf8");
const VERSION = "1.0.0";
const DESCRIPTION = [
  "Takes a picture of your whole map. Reveals caves and terrain.",
  "",
  "Map button at the top right, or F7.",
].join("\n");
const manifest = {
  manifestVersion: 1, id: "asekhan.cartographer", name: "Cartographer - Whole Map Snapshot", version: VERSION, apiVersion: 1,
  gameVersion: { minimum: "0.5.6" }, entry: "main.js", author: "Asekhan",
  description: DESCRIPTION, dependencies: [], loadOrder: 1100,
};
const bundle = [
  "// GENERATED by tools/build.cjs from src/. Edit src/, then run: node tools/build.cjs",
  `const VERSION = ${JSON.stringify(VERSION)};`,
  `const LOGIC_SRC = ${JSON.stringify(src("logic.js"))};`,
  `const WORKER_SRC = ${JSON.stringify(src("worker.js"))};`,
  src("logic.js"), src("capture.js"), src("ui.js"),
].join("\n");

// Preview: a small stylised map strip (sky, terrain, a cave, a pocket of water).
function png(w, hgt, pixel) {
  const crcT = new Uint32Array(256).map((_, n) => { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; return c >>> 0; });
  const crc = (b) => { let c = ~0; for (const x of b) c = crcT[(c ^ x) & 255] ^ (c >>> 8); return ~c >>> 0; };
  const chunk = (t, d) => { const l = Buffer.alloc(4), c = Buffer.alloc(4), td = Buffer.concat([Buffer.from(t), d]); l.writeUInt32BE(d.length); c.writeUInt32BE(crc(td)); return Buffer.concat([l, td, c]); };
  const raw = Buffer.alloc(hgt * (1 + w * 3));
  for (let y = 0; y < hgt; y++) for (let x = 0; x < w; x++) raw.set(pixel(x, y), y * (1 + w * 3) + 1 + x * 3);
  const ih = Buffer.alloc(13); ih.writeUInt32BE(w, 0); ih.writeUInt32BE(hgt, 4); ih[8] = 8; ih[9] = 2;
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk("IHDR", ih), chunk("IDAT", zlib.deflateSync(raw)), chunk("IEND", Buffer.alloc(0))]);
}
const preview = png(256, 256, (x, y) => {
  const cx = x >> 2, cy = y >> 2, n = ((cx * 73856093) ^ (cy * 19349663)) >>> 0, surf = 22 + Math.round(4 * Math.sin(cx / 7));
  if (cy < surf) return [Math.round(42 + (159 - 42) * cy / surf), Math.round(111 + 101 * cy / surf), Math.round(176 + 64 * cy / surf)];
  const cave = (cx - 30) ** 2 / 90 + (cy - 42) ** 2 / 20 < 1, pond = (cx - 46) ** 2 / 40 + (cy - 54) ** 2 / 10 < 1;
  if (cave) return [21, 33, 12];
  if (pond) return [40, 110 + (n & 15), 200];
  if (cy === surf) return [70, 160, 60];
  return cy > 50 ? [120 + (n & 15), 120 + (n & 15), 128] : [139 + (n & 15), 94 + (n & 7), 60];
});

const out = { "main.js": bundle, "modinfo.json": JSON.stringify(manifest, null, 2) + "\n" };
const dir = path.join(root, "mod");
if (process.argv.includes("--check")) {
  for (const [f, c] of Object.entries(out)) if (!fs.existsSync(path.join(dir, f)) || fs.readFileSync(path.join(dir, f), "utf8") !== c) throw Error("mod/" + f + " is stale: run node tools/build.cjs");
  console.log("mod/ is current");
} else {
  fs.mkdirSync(dir, { recursive: true });
  for (const [f, c] of Object.entries(out)) fs.writeFileSync(path.join(dir, f), c);
  if (!fs.existsSync(path.join(dir, "preview.png"))) fs.writeFileSync(path.join(dir, "preview.png"), preview);
  console.log("Built mod/ (" + (bundle.length / 1024).toFixed(0) + " KB main.js), version " + VERSION);
}
